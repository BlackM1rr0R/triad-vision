import { Link, useParams } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import { useTranslation } from 'react-i18next';
import { ArrowRight, MapPin } from 'lucide-react';
import { api } from '@/lib/api';
import { usePageTitle } from '@/lib/usePageTitle';
import { currentSiteLocale, registerCopy } from '@/i18n';
import { pagesJobs } from '@/i18n/pagesJobs';
import { PageHero, PageHeroSkeleton } from '@/components/layout/PageHero';
import { SkeletonGrid } from '@/components/ui/Skeleton';
import { buttonClass } from '@/components/ui/Button';
import { ComparableJobCard } from '@/components/jobs/CompareToggle';
import { CompareTray } from '@/components/jobs/CompareTray';
import { JobAlertForm } from '@/components/jobs/JobAlertForm';
import type { PublicVacancy } from '@/components/jobs/types';
import NotFound from '../NotFound';

registerCopy(pagesJobs);

const HERO = 'https://images.unsplash.com/photo-1601584115197-04ecc0da31d7?auto=format&fit=crop&w=2000&q=70';

interface LandingLink {
  path: string;
  label: string;
}

/** GET /api/vacancies/landing/:city/:profession (server lib/jobLandings.ts). */
export interface JobLandingResponse {
  landing: {
    path: string;
    city: string;
    profession: string;
    h1: string;
    title: string;
    description: string;
    intro: string[];
    cityName: string;
    professionName: string;
    labels: { jobs: string; sameCity: string; sameProfession: string; allJobs: string; cta: string };
  };
  items: PublicVacancy[];
  related: { sameCity: LandingLink[]; sameProfession: LandingLink[] };
}

const LinkList = ({ title, links }: { title: string; links: LandingLink[] }) =>
  links.length ? (
    <nav aria-label={title} className="card card-pad rounded-3xl">
      <h2 className="font-display text-lg font-semibold text-ink">{title}</h2>
      <ul className="mt-3 space-y-1.5">
        {links.map((l) => (
          <li key={l.path}>
            <Link to={l.path} className="inline-flex min-h-9 items-center gap-1.5 text-sm font-semibold text-link hover:underline">
              <ArrowRight className="size-4 shrink-0" aria-hidden /> {l.label}
            </Link>
          </li>
        ))}
      </ul>
    </nav>
  ) : null;

/**
 * Profession × city landing page (/jobs/in/:city/:profession): generated by the server from the live vacancies
 * — texts in the reader's language, the open vacancies, links to the neighbouring combinations. A combination
 * without vacancies is a 404 (the server answers 404 for the URL as well).
 */
export default function JobLanding() {
  const { city = '', profession = '' } = useParams();
  const { t } = useTranslation();
  const lng = currentSiteLocale();
  const { data, isLoading, isError } = useQuery({
    queryKey: ['job-landing', lng, city, profession],
    queryFn: async () =>
      (await api.get<JobLandingResponse>(`/vacancies/landing/${encodeURIComponent(city)}/${encodeURIComponent(profession)}`, { params: { lng } })).data,
    retry: false,
  });
  usePageTitle(data?.landing.h1 ?? t('jobsArea.board.title'));

  if (isLoading) {
    return (
      <>
        <PageHeroSkeleton />
        <section className="section-sm bg-sunken">
          <div className="container-x">
            <SkeletonGrid count={4} lines={3} footer className="grid-cards cards-balanced grid-cols-1 [--cols:1] md:[--cols:2] 2xl:[--cols:3]" />
          </div>
        </section>
      </>
    );
  }
  if (isError || !data) return <NotFound />;

  const { landing, items, related } = data;
  return (
    <>
      <PageHero title={landing.h1} subtitle={landing.intro[0]} image={HERO} crumb={{ to: '/jobs', label: t('nav.jobs') }}>
        <div className="mt-5 flex flex-wrap gap-2 text-sm">
          <span className="inline-flex items-center gap-1.5 rounded-full border border-line bg-card px-3 py-1.5 text-ink shadow-[var(--tv-shadow-card)]">
            <MapPin className="size-4 text-muted" aria-hidden /> {landing.cityName}
          </span>
        </div>
      </PageHero>

      <section className="section-sm bg-sunken">
        <div className="container-x grid gap-6 lg:grid-cols-[minmax(0,1fr)_20rem] lg:gap-10">
          <div className="min-w-0 space-y-6">
            {landing.intro.slice(1).map((p, i) => (
              <p key={i} className="max-w-[70ch] leading-relaxed text-ink">
                {p}
              </p>
            ))}
            <h2 className="font-display text-xl font-semibold text-ink">
              {landing.labels.jobs} ({items.length})
            </h2>
            <div className="grid-cards cards-balanced grid-cols-1 [--cols:1] md:[--cols:2]">
              {items.map((v) => (
                <ComparableJobCard key={v.id} v={v} />
              ))}
            </div>
            <JobAlertForm profession={items[0]?.profession ?? null} />
          </div>
          <aside className="min-w-0 space-y-6">
            <LinkList title={landing.labels.sameCity} links={related.sameCity} />
            <LinkList title={landing.labels.sameProfession} links={related.sameProfession} />
            <div className="flex flex-col gap-3">
              <Link to="/jobs" className={buttonClass({ variant: 'outline' })}>
                {landing.labels.allJobs}
              </Link>
              <Link to="/booking" className={buttonClass({})}>
                {landing.labels.cta}
              </Link>
            </div>
          </aside>
        </div>
      </section>
      <CompareTray />
    </>
  );
}
