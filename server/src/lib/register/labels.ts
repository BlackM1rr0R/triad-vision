export const pickLang = (v: unknown, fallback: Lang = 'az'): Lang => {
  const l = String(v ?? '').slice(0, 2).toLowerCase();
  return l === 'az' || l === 'de' || l === 'en' || l === 'ru' ? l : fallback;
};
