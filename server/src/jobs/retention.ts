import fs from 'node:fs/promises';
import path from 'node:path';
import { config } from '../config.js';
import { prisma } from '../db.js';
import { registerJob } from '../lib/scheduler.js';
import { audit } from '../lib/audit.js';
import { FINAL_STATUSES } from '../lib/caseFlow.js';
import { getRetentionSettings } from '../lib/legalSettings.js';
import { pruneAdminPageVisits } from '../lib/navModules.js';

/**
 * DSGVO storage limitation (Art. 5(1)(e), Art. 17): once a case has been closed (APPROVED /
 * REJECTED / CANCELLED) for longer than the configured retention period, the uploaded files and
 * their Document rows are deleted — including the unsigned and signed contract PDFs. The case row,
 * its requirement list and its event history stay for accountability (who decided what, when).
 * Chat messages are deleted too when `includeMessages` is on. Staff document workspaces (DocFile)
 * are never touched. The run is idempotent: purged cases get `documentsPurgedAt` and are skipped.
 */

const DAY = 24 * 60 * 60 * 1000;
export const RETENTION_EVERY_MS = DAY;
const FIRST_RUN_AFTER_MS = 10 * 60 * 1000;
/** Cases handled per run (the next run continues). */
const BATCH = 200;

/** `now` minus whole calendar months (end-of-month safe: 31 March − 1 month = 28/29 February). */
export const monthsBefore = (now: Date, months: number) => {
  const d = new Date(now);
  const day = d.getUTCDate();
  d.setUTCDate(1);
  d.setUTCMonth(d.getUTCMonth() - months);
  const lastDay = new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + 1, 0)).getUTCDate();
  d.setUTCDate(Math.min(day, lastDay));
  return d;
};

const dueWhere = (cutoff: Date) => ({
  status: { in: FINAL_STATUSES },
  closedAt: { not: null, lt: cutoff },
  documentsPurgedAt: null,
});

/** Deletes one uploaded case file (Document.storedName); returns its size, 0 when it was already gone. */
export const removeStoredFile = async (storedName: string) => {
  // storedName is generated by the server, but never let a stray value escape the upload dir.
  const file = path.join(config.uploads.privateDir, path.basename(storedName));
  try {
    const stat = await fs.stat(file);
    await fs.unlink(file);
    return stat.size;
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return 0;
    throw err;
  }
};

export interface RetentionRunResult {
  cases: number;
  documents: number;
  files: number;
  bytes: number;
  messages: number;
  failed: number;
}

let lastRunAt: Date | null = null;
let nextRunAt = new Date(Date.now() + FIRST_RUN_AFTER_MS);

export const runRetention = async (now = new Date()): Promise<RetentionRunResult> => {
  const { months, includeMessages } = await getRetentionSettings();
  const cutoff = monthsBefore(now, months);
  const due = await prisma.case.findMany({
    where: dueWhere(cutoff),
    select: { id: true, number: true },
    orderBy: { closedAt: 'asc' },
    take: BATCH,
  });
  const result: RetentionRunResult = { cases: 0, documents: 0, files: 0, bytes: 0, messages: 0, failed: 0 };

  for (const c of due) {
    try {
      const docs = await prisma.document.findMany({ where: { caseId: c.id }, select: { id: true, storedName: true } });
      // Files first: if a delete fails the rows stay, so the next run retries (no orphaned files).
      let files = 0;
      let bytes = 0;
      for (const d of docs) {
        const size = await removeStoredFile(d.storedName);
        if (size > 0) files++;
        bytes += size;
      }
      const [deletedDocs, deletedMsgs] = await prisma.$transaction(async (tx) => {
        const dd = await tx.document.deleteMany({ where: { caseId: c.id } });
        const dm = includeMessages ? await tx.caseMessage.deleteMany({ where: { caseId: c.id } }) : { count: 0 };
        await tx.case.update({ where: { id: c.id }, data: { documentsPurgedAt: now } });
        await tx.caseEvent.create({
          data: {
            caseId: c.id,
            type: 'DOCUMENTS_PURGED',
            note: `Retention ${months} months: ${dd.count} documents${includeMessages ? `, ${dm.count} messages` : ''} deleted`,
            visibleToClient: false,
          },
        });
        return [dd.count, dm.count] as const;
      });
      result.cases++;
      result.documents += deletedDocs;
      result.messages += deletedMsgs;
      result.files += files;
      result.bytes += bytes;
    } catch (err) {
      result.failed++;
      console.error(`[retention] case ${c.number} failed`, err);
    }
  }

  if (result.cases > 0 || result.failed > 0) {
    await audit({ user: undefined, ip: undefined }, 'RETENTION_PURGE', undefined, {
      ...result,
      months,
      includeMessages,
      cutoff: cutoff.toISOString(),
    });
  }
  return result;
};

/** For Admin → Settings: the configured period, the schedule and what the next run would delete. */
export const retentionStatus = async (now = new Date()) => {
  const settings = await getRetentionSettings();
  const cutoff = monthsBefore(now, settings.months);
  const [dueCases, dueNext30Days, purgedTotal, last] = await Promise.all([
    prisma.case.count({ where: dueWhere(cutoff) }),
    prisma.case.count({ where: dueWhere(monthsBefore(new Date(now.getTime() + 30 * DAY), settings.months)) }),
    prisma.case.count({ where: { documentsPurgedAt: { not: null } } }),
    prisma.auditLog.findFirst({ where: { action: 'RETENTION_PURGE' }, orderBy: { createdAt: 'desc' } }),
  ]);
  return {
    settings,
    cutoff,
    dueCases,
    dueNext30Days,
    purgedTotal,
    lastRunAt,
    nextRunAt,
    lastPurge: last ? { at: last.createdAt, details: last.details } : null,
  };
};

registerJob({
  name: 'retention',
  everyMs: RETENTION_EVERY_MS,
  firstRunAfterMs: FIRST_RUN_AFTER_MS,
  run: async () => {
    try {
      const r = await runRetention();
      if (r.cases || r.failed) console.log(`[retention] purged ${r.cases} cases, ${r.documents} documents (${r.failed} failed)`);
      // Admin page usage statistics are kept for 400 days.
      await pruneAdminPageVisits().catch((err) => console.error('[retention] page usage prune failed', err));
    } finally {
      lastRunAt = new Date();
      nextRunAt = new Date(lastRunAt.getTime() + RETENTION_EVERY_MS);
    }
  },
});
