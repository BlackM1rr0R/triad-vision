#!/usr/bin/env node
/**
 * Metro does not tree-shake, so `import { X } from 'lucide-react-native'` would bundle all ~1900 icons.
 * This script scans src/ for the icons we use and writes src/components/icons.ts with per-icon deep imports.
 * App code imports icons from '@/components/icons'. Run `npm run gen-icons` after using a new icon.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src');
const out = path.join(src, 'components', 'icons.ts');
const index = await readFile(path.join(root, 'node_modules/lucide-react-native/dist/esm/lucide-react-native.mjs'), 'utf8');

// alias name → icon file (e.g. CheckCircle2 → circle-check)
const fileOf = new Map();
for (const m of index.matchAll(/export \{([^}]+)\} from '\.\/icons\/([^']+)\.mjs'/g)) {
  for (const part of m[1].split(',')) {
    const name = part.trim().split(/\s+as\s+/)[1];
    if (name) fileOf.set(name, m[2]);
  }
}

const walk = async (dir) => {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(entries.map((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])));
  return files.flat().filter((f) => /\.tsx?$/.test(f) && f !== out);
};

const used = new Set();
for (const file of await walk(src)) {
  const code = await readFile(file, 'utf8');
  for (const m of code.matchAll(/import\s*\{([^}]+)\}\s*from\s*'(?:lucide-react-native|@\/components\/icons)'/g)) {
    for (const part of m[1].split(',')) {
      const name = part.replace(/^\s*type\s+/, '').trim().split(/\s+as\s+/)[0];
      if (name && /^[A-Z]/.test(name) && name !== 'LucideProps' && name !== 'LucideIcon') used.add(name);
    }
  }
}

const missing = [...used].filter((n) => !fileOf.has(n));
if (missing.length) {
  console.error('Unknown lucide icons:', missing.join(', '));
  process.exit(1);
}

const names = [...used].sort();
const lines = [
  '// Generated by scripts/gen-icons.mjs — do not edit by hand.',
  '// Deep imports keep the bundle small (Metro does not tree-shake the lucide barrel file).',
  "export type { LucideIcon, LucideProps } from 'lucide-react-native';",
  ...names.map((n) => `export { default as ${n} } from 'lucide-react-native/icons/${fileOf.get(n)}';`),
  '',
];
await writeFile(out, lines.join('\n'), 'utf8');
console.log(`wrote ${path.relative(root, out)} (${names.length} icons)`);
